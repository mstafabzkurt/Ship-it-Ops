      -- Only high-confidence severe roots with low Turkish-word collision risk use substring matching.
      when normalized_term = any (array[
        'amcik', 'asshole', 'fuck', 'kahpe', 'kaltak', 'kurwa', 'orospu', 'pezevenk', 'siktir', 'whore', 'yavsak'
