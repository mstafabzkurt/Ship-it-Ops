      when normalized_term = any (array[
        'ag', 'allah', 'am', 'ana', 'anal', 'aq', 'ass', 'basur', 'biting', 'boner', 'cif', 'cikar', 'cim', 'emi', 'feristah', 'geber', 'hosafi', 'kaka', 'kasar', 'kayyum', 'krar', 'mal', 'malak', 'manyak', 'meme', 'oglan', 'okuz', 'penis', 'pipi', 'revizyonist', 'saksofon', 'shit', 'bitch', 'veled', 'yalama', 'yalarim', 'yogurtlayam'
